const EMPTY_TAGS = Object.freeze([]);

function buildTagsByCommand(groups) {
  const mutable = new Map();
  for (const [tag, commands] of Object.entries(groups)) {
    for (const command of commands) {
      const tags = mutable.get(command) ?? [];
      if (!tags.includes(tag)) tags.push(tag);
      mutable.set(command, tags);
    }
  }
  return new Map(
    [...mutable.entries()].map(([command, tags]) => [command, Object.freeze(tags)])
  );
}

const TAGS_BY_COMMAND = buildTagsByCommand(GEOGEBRA_COMMAND_TAXONOMY);

/**
 * Returns the stable, de-duplicated taxonomy tags for an exact canonical command.
 * Unknown commands intentionally return the same frozen empty array.
 */
export function getGeoGebraCommandTaxonomyTags(command) {
  return TAGS_BY_COMMAND.get(String(command ?? "").trim()) ?? EMPTY_TAGS;
}
